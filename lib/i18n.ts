// Context
import React from 'react'
interface I18nContextType { locale: Locale; t: (key: string) => string }
const I18nContext = createContext<I18nContextType>({ locale: 'pt-BR', t: (k) => k })

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>('pt-BR')

  useEffect(() => {
    setLocaleState(getLocale())
  }, [])

  const t = (key: string): string =>
    translations[locale]?.[key] ?? translations['pt-BR'][key] ?? key

  return createElement(I18nContext.Provider, { value: { locale, t } }, children)
}

export function useI18n() {
  return useContext(I18nContext)
}

export function t(key: string): string {
  const locale = getLocale()
  return translations[locale]?.[key] ?? translations['pt-BR'][key] ?? key
}
